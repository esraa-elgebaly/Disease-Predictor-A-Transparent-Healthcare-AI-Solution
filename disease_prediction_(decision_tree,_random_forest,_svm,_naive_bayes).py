def build_input_vector(symptoms_string):
    """Convert comma-separated symptoms string to a DataFrame matching trained columns."""
    # Normalize and split input
    if not symptoms_string:
        return None, "No symptoms provided."
    toks = [s.strip() for s in symptoms_string.split(",") if s.strip()]
    if len(toks) == 0:
        return None, "No valid symptoms parsed from input."

    # Build binary vector
    input_vec = [1 if s in symptoms else 0 for s in symptoms]
    input_df = pd.DataFrame([input_vec], columns=symptoms)
    return input_df, None

def safe_predict(symptoms_text):
    """Return predictions and confidences for RF, NB, SVM and an ensemble."""
    try:
        input_df, err = build_input_vector(symptoms_text)
        if err:
            return {"error": err}
        # individual preds
        rf_idx = rf_model.predict(input_df)[0]
        nb_idx = nb_model.predict(input_df)[0]
        svm_idx = svm_model.predict(input_df)[0]

        # decode labels
        rf_label = encoder.inverse_transform([rf_idx])[0]
        nb_label = encoder.inverse_transform([nb_idx])[0]
        svm_label = encoder.inverse_transform([svm_idx])[0]

        # confidences: try predict_proba, fallback to 1.0
        def get_conf(model):
            try:
                probs = model.predict_proba(input_df)[0]
                return float(np.max(probs))
            except Exception:
                return 1.0

        rf_conf = get_conf(rf_model)
        nb_conf = get_conf(nb_model)
        svm_conf = get_conf(svm_model)

        # ensemble: majority vote on labels; if tie, use averaged probability vector
        try:
            ensemble_label = mode([rf_label, nb_label, svm_label])
        except Exception:
            # compute averaged probability vector across models (align to encoder class indices)
            def prob_vec(m):
                try:
                    return m.predict_proba(input_df)[0]
                except Exception:
                    vec = np.zeros(n_classes)
                    pred = m.predict(input_df)[0]
                    vec[pred] = 1.0
                    return vec
            avg = (prob_vec(rf_model) + prob_vec(nb_model) + prob_vec(svm_model)) / 3.0
            idx = int(np.argmax(avg))
            ensemble_label = encoder.inverse_transform([idx])[0]

        # ensemble confidence: average of chosen class probabilities
        # compute averaged probs as above
        p_rf = rf_model.predict_proba(input_df)[0] if hasattr(rf_model, "predict_proba") else np.eye(n_classes)[rf_idx]
        p_nb = nb_model.predict_proba(input_df)[0] if hasattr(nb_model, "predict_proba") else np.eye(n_classes)[nb_idx]
        p_svm = svm_model.predict_proba(input_df)[0] if hasattr(svm_model, "predict_proba") else np.eye(n_classes)[svm_idx]
        avg_probs = (p_rf + p_nb + p_svm) / 3.0
        ensemble_conf = float(np.max(avg_probs))
        ensemble_label_prob = encoder.inverse_transform([int(np.argmax(avg_probs))])[0]

        return {
            "Random Forest": {"label": rf_label, "confidence": round(rf_conf, 3)},
            "Naive Bayes": {"label": nb_label, "confidence": round(nb_conf, 3)},
            "SVM": {"label": svm_label, "confidence": round(svm_conf, 3)},
            "Ensemble (vote/avg)": {"label": ensemble_label, "confidence": round(ensemble_conf, 3)}
        }
    except NotFittedError as nf:
        return {"error": "Model not fitted. Train models first."}
    except Exception:
        traceback.print_exc()
        return {"error": "Prediction failed. See server logs."}

